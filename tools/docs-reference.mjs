// Generates docs/reference/{hooks,settings,surface}.md from core hooks, the naming registry, and the settings schema.
// Usage: node tools/docs-reference.mjs [--check]   (--check fails when code or committed references drift)
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fromRoot } from './lib/paths.mjs';

const registry = JSON.parse(readFileSync(fromRoot('docs/spec/naming-registry.json'), 'utf8'));
const schema = JSON.parse(readFileSync(fromRoot('packages/theme-core/schema/settings.schema.json'), 'utf8'));
const NOTES = {
  hooks:
    '<!-- Generated by tools/docs-reference.mjs from packages/theme-core/src and docs/spec/naming-registry.json. Do not edit. -->\n',
  settings:
    '<!-- Generated by tools/docs-reference.mjs from packages/theme-core/schema/settings.schema.json. Do not edit. -->\n',
  surface: '<!-- Generated by tools/docs-reference.mjs from docs/spec/naming-registry.json. Do not edit. -->\n',
};

/** Groups hook names by module (`joo/<module>/...`). */
export function hooksByModule(hooks) {
  const groups = {};
  for (const hook of hooks) (groups[hook.split('/')[1]] ??= []).push(hook);
  return groups;
}

function skipQuoted(source, index) {
  const quote = source[index];
  for (let i = index + 1; i < source.length; i += 1) {
    if (source[i] === '\\') i += 1;
    else if (source[i] === quote) return i + 1;
  }
  return source.length;
}

function skipComment(source, index) {
  if (source[index] === '/' && source[index + 1] === '*') {
    const end = source.indexOf('*/', index + 2);
    return end === -1 ? source.length : end + 2;
  }
  if ((source[index] === '/' && source[index + 1] === '/') || source[index] === '#') {
    const end = source.indexOf('\n', index + 1);
    return end === -1 ? source.length : end + 1;
  }
  return index;
}

function splitPhpArguments(source, openParen) {
  const closing = new Map([
    ['(', ')'],
    ['[', ']'],
    ['{', '}'],
  ]);
  const stack = [')'];
  const args = [];
  let start = openParen + 1;

  for (let i = start; i < source.length; i += 1) {
    if (source[i] === "'" || source[i] === '"') {
      i = skipQuoted(source, i) - 1;
      continue;
    }
    const commentEnd = skipComment(source, i);
    if (commentEnd !== i) {
      i = commentEnd - 1;
      continue;
    }

    if (closing.has(source[i])) {
      stack.push(closing.get(source[i]));
      continue;
    }

    if ([')', ']', '}'].includes(source[i])) {
      if (stack.at(-1) !== source[i]) throw new Error('Unbalanced PHP call arguments');
      stack.pop();
      if (stack.length === 0) {
        const last = source.slice(start, i).trim();
        if (last || args.length) args.push(last);
        return { args, end: i + 1 };
      }
      continue;
    }

    if (source[i] === ',' && stack.length === 1) {
      args.push(source.slice(start, i).trim());
      start = i + 1;
    }
  }

  throw new Error('Unclosed PHP call arguments');
}

function hookCallAt(source, index) {
  return source.slice(index).match(/^(?:\\?[A-Za-z_][A-Za-z0-9_]*\\)*Hooks::(filter|action)\s*\(/);
}

function resolveHookName(expression, registryHooks) {
  const value = expression.trim();
  const literal = value.match(/^(['"])(joo\/[^'"]+)\1$/);
  if (literal) return literal[2];

  const formatted = value.match(/^sprintf\s*\(\s*(['"])(joo\/[^'"]+)\1\s*,/);
  if (!formatted) return null;

  const format = formatted[2];
  const dynamicFormat = format.replace(/%s/g, '{param}');
  const template = registryHooks.find(
    (hook) => hook.includes('{') && hook.replace(/\{[^}]+\}/g, '{param}') === dynamicFormat
  );
  return template ?? dynamicFormat;
}

function argumentLabel(expression, position, kind, hookName) {
  if (kind === 'filter' && position === 0) return 'value';
  const aliases = {
    'joo/assets/register': ['assetRegistry'],
    'joo/core/ready': ['container'],
    'joo/seo/allow_external_canonical': ['value', 'canonicalUrl'],
  }[hookName];
  if (aliases?.[position]) return aliases[position];
  const value = expression.trim();
  const contextMethod = value.match(/^\$this->([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*\)$/);
  if (contextMethod) return contextMethod[1];
  const property = value.match(/^\$this->([A-Za-z_][A-Za-z0-9_]*)$/);
  if (property) return property[1];
  const propertyId = value.match(/\$([A-Za-z_][A-Za-z0-9_]*)\s*->\s*ID\b/);
  if (propertyId) return `${propertyId[1]}Id`;
  const namedProperty = value.match(/\$([A-Za-z_][A-Za-z0-9_]*)\s*\[\s*['"]name['"]\s*\]/);
  if (namedProperty) return `${namedProperty[1]}Name`;
  const variable = value.match(/^\$([A-Za-z_][A-Za-z0-9_]*)$/);
  if (variable) {
    if (variable[1] === 'ctx') return 'context';
    if (variable[1] === 'attrs') return 'attributes';
    return variable[1];
  }
  return `argument${position + 1}`;
}

/** Extract filter/action invocations in a PHP source string. */
export function hooksFromPhp(source, sourcePath, registryHooks) {
  const hooks = [];
  const errors = [];

  for (let i = 0; i < source.length;) {
    if (source[i] === "'" || source[i] === '"') {
      i = skipQuoted(source, i);
      continue;
    }
    const commentEnd = skipComment(source, i);
    if (commentEnd !== i) {
      i = commentEnd;
      continue;
    }

    const call = hookCallAt(source, i);
    if (!call) {
      i += 1;
      continue;
    }

    try {
      const openParen = i + call[0].lastIndexOf('(');
      const { args, end } = splitPhpArguments(source, openParen);
      const hook = args.length ? resolveHookName(args[0], registryHooks) : null;
      const line = source.slice(0, i).split('\n').length;
      if (!hook) {
        errors.push(`${sourcePath}:${line}: could not resolve hook name in ${call[1]} call`);
      } else {
        const kind = call[1];
        const callbackArgs = args.slice(1).map((arg, position) => argumentLabel(arg, position, kind, hook));
        hooks.push({ name: hook, kind, arguments: callbackArgs, source: `${sourcePath}:${line}` });
      }
      i = end;
    } catch (error) {
      const line = source.slice(0, i).split('\n').length;
      errors.push(`${sourcePath}:${line}: ${error.message}`);
      i += call[0].length;
    }
  }

  return { hooks, errors };
}

function phpFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? phpFiles(path) : entry.isFile() && path.endsWith('.php') ? [path] : [];
    });
}

function codeFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      if (['node_modules', 'vendor', 'build', 'core', '.git', 'tests', 'design'].includes(entry.name)) return [];
      const path = join(directory, entry.name);
      return entry.isDirectory()
        ? codeFiles(path)
        : entry.isFile() && /\.(php|js|mjs|json|html)$/.test(path) && !/\.test\.js$/.test(path)
          ? [path]
          : [];
    });
}

function mergeHooks(hooks) {
  const byName = new Map();
  const errors = [];
  for (const hook of hooks) {
    const current = byName.get(hook.name);
    if (!current) {
      byName.set(hook.name, { ...hook, sources: [hook.source] });
      continue;
    }
    current.sources.push(hook.source);
    if (current.kind !== hook.kind) {
      errors.push(`${hook.name}: used as both a filter and an action (${current.sources.join(', ')})`);
      continue;
    }
    if (current.arguments.length !== hook.arguments.length) {
      errors.push(`${hook.name}: inconsistent argument counts (${current.sources.join(', ')})`);
      continue;
    }
    current.arguments = current.arguments.map((argument, index) =>
      argument === hook.arguments[index] ? argument : `argument${index + 1}`
    );
  }
  return { hooks: [...byName.values()].sort((a, b) => a.name.localeCompare(b.name)), errors };
}

/** Read and merge hooks fired by packages/theme-core/src. */
export function coreHooks(sourceRoot, registryHooks) {
  const found = [];
  const errors = [];
  for (const file of phpFiles(sourceRoot)) {
    const source = readFileSync(file, 'utf8');
    const relativePath = file.replace(`${sourceRoot}/`, '');
    const result = hooksFromPhp(source, relativePath, registryHooks);
    found.push(...result.hooks);
    errors.push(...result.errors);
  }
  const merged = mergeHooks(found);
  errors.push(...merged.errors);
  return { hooks: merged.hooks, errors };
}

/** Compare the observed public hook names with the exact hook list in the naming registry. */
export function hookRegistryDrift(hooks, registryHooks) {
  const sourceNames = new Set(hooks.map((hook) => hook.name));
  const registryNames = new Set(registryHooks);
  return {
    missingFromRegistry: [...sourceNames].filter((name) => !registryNames.has(name)).sort(),
    missingFromSource: [...registryNames].filter((name) => !sourceNames.has(name)).sort(),
  };
}

/** Return naming-registry surface entries which no longer appear in code. */
export function surfaceRegistryDrift(reg, source) {
  const lists = [
    'options',
    'transients',
    'postMeta',
    'postMetaInternal',
    'termMeta',
    'userMeta',
    'postTypes',
    'restRoutes',
    'blocks',
    'customElements',
  ];
  const missing = [];
  for (const list of lists) {
    for (const item of reg[list] ?? []) {
      const fragments = item.split(/\{[^}]+\}/g).filter(Boolean);
      const found = fragments.length ? fragments.every((fragment) => source.includes(fragment)) : source.includes(item);
      if (!found) missing.push(`${list}: ${item}`);
    }
  }
  return missing.sort();
}

export function hooksPage(hooks) {
  const groups = {};
  for (const hook of hooks) (groups[hook.name.split('/')[1]] ??= []).push(hook);
  const body = Object.entries(groups)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([module, entries]) => {
      const rows = entries
        .sort((a, b) => a.name.localeCompare(b.name))
        .map((hook) => {
          const args = hook.arguments.length ? hook.arguments.map((arg) => `\`$${arg}\``).join(', ') : 'none';
          return `- \`${hook.name}\` — ${hook.kind === 'filter' ? 'Filter' : 'Action'}; arguments: ${args}.`;
        });
      return `## ${module}\n\n${rows.join('\n')}\n`;
    })
    .join('\n');
  return `${NOTES.hooks}\n# Hooks\n\nEach entry is a filter or action fired by \`packages/theme-core/src\`. Arguments are listed in callback order; filters receive the filtered value first. Hook names are governed by \`docs/spec/naming-registry.json\`.\n\n${body}`;
}

export function settingsPage(sch) {
  const rows = Object.entries(sch.settings).map(([key, s]) => {
    const def = JSON.stringify(s.default);
    return `| \`${key}\` | ${s.type} | \`${def}\` | ${s.group} | ${String(s.description ?? s.title).replace(/\|/g, '/')} |`;
  });
  return `${NOTES.settings}\n# Settings\n\nPrecedence: filter \`joo/settings/value\`, then the value saved in the admin, then the theme manifest, then the default below.\n\n| Key | Type | Default | Group | Description |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`;
}

export function surfacePage(reg) {
  const list = (title, items) => `## ${title}\n\n${items.map((i) => `- \`${i}\``).join('\n')}\n`;
  return `${NOTES.surface}\n# REST routes, blocks, post types and stored data\n\nREST namespace: \`joo/v1\`.\n\n${[
    list('REST routes', reg.restRoutes),
    list('Blocks', reg.blocks),
    list('Custom elements', reg.customElements),
    list('Post types', reg.postTypes),
    list('Options', reg.options),
    list('Post meta', [...reg.postMeta, ...reg.postMetaInternal]),
    list('Term meta', reg.termMeta),
    list('User meta', reg.userMeta),
  ].join('\n')}`;
}

export function checkGeneratedFiles(files, root = fromRoot()) {
  return Object.entries(files)
    .filter(([path, content]) => {
      const file = join(root, path);
      return !existsSync(file) || readFileSync(file, 'utf8') !== content;
    })
    .map(([path]) => path);
}

function referenceFiles(hooks) {
  return {
    'docs/reference/hooks.md': hooksPage(hooks),
    'docs/reference/settings.md': settingsPage(schema),
    'docs/reference/surface.md': surfacePage(registry),
  };
}

function verifyCodeReferences(hooks) {
  const errors = [];
  const drift = hookRegistryDrift(hooks, registry.hooks);
  for (const name of drift.missingFromRegistry) errors.push(`hook not in naming registry: ${name}`);
  for (const name of drift.missingFromSource)
    errors.push(`registered hook is not fired in packages/theme-core/src: ${name}`);

  const sourceFiles = [
    ...phpFiles(fromRoot('packages/theme-core/src')),
    ...['packages/theme-core/resources', 'plugins/jooservices-resume', 'themes', 'docker/scripts'].flatMap(
      (directory) => codeFiles(fromRoot(directory))
    ),
  ];
  const source = sourceFiles
    .filter((file) => existsSync(file) && statSync(file).isFile())
    .map((file) => readFileSync(file, 'utf8'))
    .join('\n');
  for (const item of surfaceRegistryDrift(registry, source))
    errors.push(`surface registry entry is not in code: ${item}`);
  return errors;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { hooks, errors: hookErrors } = coreHooks(fromRoot('packages/theme-core/src'), registry.hooks);
  const errors = [...hookErrors, ...verifyCodeReferences(hooks)];
  if (errors.length) {
    console.error(errors.map((error) => `drift: ${error}`).join('\n'));
    process.exitCode = 1;
  } else {
    const files = referenceFiles(hooks);
    if (check) {
      const stale = checkGeneratedFiles(files);
      if (stale.length) {
        for (const path of stale) console.error(`stale: ${path} (run: node tools/docs-reference.mjs)`);
        process.exitCode = 1;
      } else console.log(`reference docs match source (${Object.keys(files).length} pages)`);
    } else {
      for (const [path, content] of Object.entries(files)) writeFileSync(fromRoot(path), content);
      console.log(`wrote ${Object.keys(files).length} reference pages`);
    }
  }
}

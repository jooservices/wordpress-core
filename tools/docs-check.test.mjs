// @vitest-environment node
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { checkBuyerDocs, checkMarkdownFile, headingSlugs, markdownLinks } from './docs-check.mjs';

let root;

function fixture() {
  root = mkdtempSync(join(tmpdir(), 'jooservices-docs-'));
  mkdirSync(join(root, 'docs', 'buyer', 'assets'), { recursive: true });
  writeFileSync(
    join(root, 'docs', 'buyer', 'index.md'),
    '# Guide\n\n## Release notes for buyers\n\n![Screen](assets/home-desktop-dark.png)\n'
  );
  writeFileSync(join(root, 'docs', 'buyer', 'assets', 'home-desktop-dark.png'), 'generated');
  return root;
}

afterEach(() => {
  if (root) rmSync(root, { recursive: true, force: true });
  root = undefined;
});

describe('buyer documentation links', () => {
  it('extracts inline link and image targets', () => {
    expect(
      markdownLinks('[page](guide.md#start) ![screen](<assets/site image.png>) [web](https://example.test)')
    ).toEqual(['guide.md#start', 'assets/site image.png', 'https://example.test']);
  });

  it('creates stable heading slugs including duplicate headings', () => {
    expect(headingSlugs('# Hello, world!\n## Hello, world!\n## Hello, world!')).toEqual(
      new Set(['hello-world', 'hello-world-1', 'hello-world-2'])
    );
  });

  it('accepts existing files, generated images, anchors, and external URLs', () => {
    const project = fixture();
    writeFileSync(
      join(project, 'docs', 'buyer', 'start.md'),
      '[release](index.md#release-notes-for-buyers) ![screen](assets/home-desktop-dark.png) [external](https://example.test)'
    );
    expect(checkBuyerDocs(project)).toEqual([]);
  });

  it('resolves directory links to README files and reports malformed escapes', () => {
    const project = fixture();
    const directory = join(project, 'docs', 'buyer', 'topic');
    mkdirSync(directory);
    writeFileSync(join(directory, 'README.md'), '# Topic page\n');
    const filePath = join(project, 'docs', 'buyer', 'start.md');
    writeFileSync(filePath, '[topic](topic/#topic-page) [bad](%E0)');
    expect(checkMarkdownFile(filePath, project)).toEqual(['docs/buyer/start.md: malformed link %E0']);
  });

  it('reports missing files and heading fragments', () => {
    const project = fixture();
    const filePath = join(project, 'docs', 'buyer', 'start.md');
    writeFileSync(filePath, '[missing](nope.md) [anchor](index.md#unknown)');
    expect(checkMarkdownFile(filePath, project)).toEqual([
      'docs/buyer/start.md: missing nope.md',
      'docs/buyer/start.md: missing heading index.md#unknown',
    ]);
  });

  it('rejects buyer screenshots outside the showcase runner output names', () => {
    const project = fixture();
    const filePath = join(project, 'docs', 'buyer', 'start.md');
    writeFileSync(filePath, '![manual screenshot](assets/manual-capture.png)');
    expect(checkMarkdownFile(filePath, project)).toEqual([
      'docs/buyer/start.md: screenshot is not generated by tools/screenshots.mjs: assets/manual-capture.png',
    ]);
  });

  it('requires at least one buyer guide page', () => {
    root = mkdtempSync(join(tmpdir(), 'jooservices-empty-docs-'));
    expect(checkBuyerDocs(root)).toEqual(['docs/buyer: no Markdown documentation found']);
  });
});

// Builds translation files: copies the POT files made by WP-CLI (make i18n), generates the Vietnamese .po from the
// dictionary (languages/vi.json), compiles .mo with msgfmt and fails when a shipped string has no translation.
// Usage: node tools/i18n.mjs [--check]
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fromRoot } from './lib/paths.mjs';

const targets = [
  { name: 'joo-core', dir: 'packages/theme-core/languages' },
  { name: 'jooservices-content', dir: 'plugins/jooservices-content/languages' },
];

/** Reads the msgids of a POT file: list of {id, plural}. */
export function parsePot(text) {
  const entries = [];
  for (const block of text.split(/\n\n+/)) {
    const id = /^msgid ((?:".*"\n?)+)/m.exec(block);
    if (!id) continue;
    const join = (raw) => [...raw.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => m[1]).join('');
    const key = join(id[1]);
    if (!key) continue;
    const plural = /^msgid_plural ((?:".*"\n?)+)/m.exec(block);
    entries.push({ id: key, plural: plural ? join(plural[1]) : null });
  }
  return entries;
}

const unescape = (s) => s.replace(/\\"/g, '"').replace(/\\\\/g, '\\').replace(/\\n/g, '\n');
const escape = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');

let failed = false;
for (const target of targets) {
  const dir = fromRoot(target.dir);
  const artifact = fromRoot('artifacts/i18n', `${target.name}.pot`);
  const pot = join(dir, `${target.name}.pot`);
  if (!process.argv.includes('--check') && existsSync(artifact)) {
    mkdirSync(dir, { recursive: true });
    copyFileSync(artifact, pot);
  }
  if (!existsSync(pot)) {
    console.log(`skip ${target.name}: no POT file (run make i18n)`);
    continue;
  }
  const dictPath = join(dir, 'vi.json');
  const dict = existsSync(dictPath) ? JSON.parse(readFileSync(dictPath, 'utf8')) : {};
  const entries = parsePot(readFileSync(pot, 'utf8')).filter((e, i, all) => all.findIndex((x) => x.id === e.id) === i);
  const missing = entries.filter((e) => !(unescape(e.id) in dict));
  const used = new Set(entries.map((e) => unescape(e.id)));
  const unused = Object.keys(dict).filter((k) => !used.has(k));
  const lines = [
    `# Vietnamese translation of ${target.name}. Generated by tools/i18n.mjs from languages/vi.json.`,
    'msgid ""',
    'msgstr ""',
    '"Project-Id-Version: ' + target.name + '\\n"',
    '"Language: vi\\n"',
    '"MIME-Version: 1.0\\n"',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    '"Plural-Forms: nplurals=1; plural=0;\\n"',
    '',
  ];
  for (const e of entries) {
    const tr = dict[unescape(e.id)];
    if (tr === undefined) continue;
    lines.push(`msgid "${e.id}"`);
    if (e.plural !== null) {
      lines.push(`msgid_plural "${e.plural}"`, `msgstr[0] "${escape(Array.isArray(tr) ? tr[0] : tr)}"`);
    } else lines.push(`msgstr "${escape(tr)}"`);
    lines.push('');
  }
  if (missing.length) {
    failed = true;
    console.log(`FAIL ${target.name}: ${missing.length} untranslated Vietnamese string(s):`);
    for (const e of missing.slice(0, 20)) console.log('  - ' + e.id.slice(0, 100));
  }
  if (unused.length) console.log(`warn ${target.name}: ${unused.length} dictionary entr(y/ies) no longer used`);
  if (!process.argv.includes('--check')) {
    const po = join(dir, `${target.name}-vi.po`);
    writeFileSync(po, lines.join('\n'));
    execFileSync('msgfmt', ['--check-format', '-o', join(dir, `${target.name}-vi.mo`), po]);
    console.log(`ok   ${target.name}: ${entries.length} strings, vi.po and vi.mo written`);
  } else if (!missing.length) console.log(`ok   ${target.name}: every string is translated`);
}
process.exit(failed ? 1 : 0);

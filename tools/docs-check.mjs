// Verifies local Markdown links and heading fragments in the buyer documentation.
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fromRoot } from './lib/paths.mjs';
import { isGeneratedScreenshot } from './screenshots.mjs';

/** Return inline Markdown links and images with their target paths. */
export function markdownLinks(markdown) {
  const links = [];
  const pattern = /!?\[[^\]]*\]\((<[^>]+>|[^\s)]+)(?:\s+["'][^"']*["'])?\)/g;
  for (const match of markdown.matchAll(pattern)) {
    const target = match[1].startsWith('<') ? match[1].slice(1, -1) : match[1];
    links.push(target);
  }
  return links;
}

/** Convert a Markdown heading to the fragment format used by GitHub Pages. */
export function headingSlugs(markdown) {
  const counts = new Map();
  const slugs = new Set();
  for (const [, source] of markdown.matchAll(/^#{1,6}\s+(.+?)\s*#*\s*$/gm)) {
    const base = source
      .replace(/`([^`]*)`/g, '$1')
      .toLowerCase()
      .replace(/[^\p{L}\p{N}_\-\s]/gu, '')
      .trim()
      .replace(/\s+/g, '-');
    const count = counts.get(base) ?? 0;
    counts.set(base, count + 1);
    slugs.add(count ? `${base}-${count}` : base);
  }
  return slugs;
}

function markdownTarget(target, source) {
  const [pathPart, fragment] = target.split('#', 2);
  const filePath = resolve(dirname(source), decodeURIComponent(pathPart || ''));
  let resolvedFile = filePath;
  if (existsSync(filePath) && statSync(filePath).isDirectory()) {
    resolvedFile = ['README.md', 'index.md'].map((name) => join(filePath, name)).find(existsSync) ?? filePath;
  }
  return { filePath: resolvedFile, fragment: fragment ? decodeURIComponent(fragment) : '' };
}

/** Check links in a Markdown file and return one diagnostic per broken target. */
export function checkMarkdownFile(filePath, root) {
  const markdown = readFileSync(filePath, 'utf8');
  const errors = [];
  for (const target of markdownLinks(markdown)) {
    if (/^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(target)) continue;
    const pathPart = target.split('#', 1)[0];
    if (extname(pathPart).toLowerCase() === '.png') {
      const filename = pathPart.split('/').at(-1);
      if (!isGeneratedScreenshot(filename)) {
        errors.push(`${relative(root, filePath)}: screenshot is not generated by tools/screenshots.mjs: ${target}`);
        continue;
      }
    }
    let resolved;
    try {
      resolved = markdownTarget(target, filePath);
    } catch {
      errors.push(`${relative(root, filePath)}: malformed link ${target}`);
      continue;
    }
    if (!existsSync(resolved.filePath)) {
      errors.push(`${relative(root, filePath)}: missing ${target}`);
      continue;
    }
    if (resolved.fragment && extname(resolved.filePath).toLowerCase() === '.md') {
      const slugs = headingSlugs(readFileSync(resolved.filePath, 'utf8'));
      if (!slugs.has(resolved.fragment)) errors.push(`${relative(root, filePath)}: missing heading ${target}`);
    }
  }
  return errors;
}

function markdownFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? markdownFiles(path) : entry.isFile() && entry.name.endsWith('.md') ? [path] : [];
  });
}

/** Validate all Markdown links beneath docs/buyer and return any failures. */
export function checkBuyerDocs(root = fromRoot()) {
  const buyerDir = join(root, 'docs', 'buyer');
  const files = markdownFiles(buyerDir);
  if (!files.length) return ['docs/buyer: no Markdown documentation found'];
  return files.flatMap((filePath) => checkMarkdownFile(filePath, root));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const errors = checkBuyerDocs();
  if (errors.length) {
    console.error(errors.map((error) => `ERROR ${error}`).join('\n'));
    process.exitCode = 1;
  } else {
    console.log('buyer documentation links and anchors are valid');
  }
}

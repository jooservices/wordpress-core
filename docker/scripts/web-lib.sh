#!/usr/bin/env bash
# Helpers for the shared PHP web runtime (wp-web, see Workspaces dockers/README.md). Sourced by wp-task.sh.
# Needs: ROOT, workspaces_root, theme, get_env. The web container is one at a time; callers hold the shared lock.
# The marketplace mode mounts the packaged theme and plugin instead of the sources (set WEB_MARKETPLACE=1).

WEB_NAME="${WP_WEB_NAME:-workspaces-wp-web}"
export WP_WEB_NAME="$WEB_NAME"
export WP_WEB_PHP="${WP_WEB_PHP:-${WP_PHP_VERSION:-8.3}}"
web_override="$ROOT/.tmp/wp-web-override.yaml"

web_shared() { "$workspaces_root/scripts/docker/shared" "$@"; }

# Runs a command in the web container as www-data. Leading "-e KEY=VALUE" pairs become environment variables.
webx() {
  local opts=()
  while [[ "${1:-}" == -e ]]; do opts+=(-e "$2"); shift 2; done
  docker exec -i ${opts[@]+"${opts[@]}"} -u www-data -w /var/www/html "$WEB_NAME" "$@"
}

web_site_url() { printf '%s' "${WP_SITE_URL:-$(get_env WP_SITE_URL)}"; }

# Writes the override file with this worktree's mounts. Values stay in the environment, never in the file.
web_write_override() {
  local uploads="joowt-$(get_env DB_NAME)-uploads" slug dir
  mkdir -p "$(dirname "$web_override")"
  {
    echo "# generated by docker/scripts/web-lib.sh: do not edit"
    echo "services:"
    echo "  wp-web:"
    echo "    environment:"
    echo "      WORDPRESS_DB_HOST: mariadb:3306"
    echo '      WORDPRESS_DB_NAME: ${WEB_DB_NAME}'
    echo '      WORDPRESS_DB_USER: ${WEB_DB_USER}'
    echo '      WORDPRESS_DB_PASSWORD: ${WEB_DB_PASSWORD}'
    echo '      WP_SITE_URL: ${WEB_SITE_URL}'
    echo '      WP_ADMIN_USER: ${WEB_ADMIN_USER}'
    echo '      WP_ADMIN_PASSWORD: ${WEB_ADMIN_PASSWORD}'
    echo '      WP_ADMIN_EMAIL: ${WEB_ADMIN_EMAIL}'
    echo '      WP_VERSION: ${WEB_WP_VERSION}'
    echo "      MAIL_HOST: mailpit"
    echo "      MAIL_PORT_SMTP: '1025'"
    # Test mode replaces the default web root (the whole Workspaces tree) with this ticket's own WordPress root.
    echo "    volumes: !override"
    echo "      - wp_web_root:/var/www/html"
    echo "      - wpcli_cache:/cache"
    echo "      - wp_uploads:/var/www/html/wp-content/uploads"
    echo "      - php_logs:/var/log/php"
    echo "      - wp_tests_lib:/tmp/wordpress-tests-lib"
    echo "      - $ROOT/docker/php.ini:/usr/local/etc/php/conf.d/zz-joowt.ini:ro"
    echo "      - $ROOT/docker/mu-plugins:/var/www/html/wp-content/mu-plugins:ro"
    echo "      - $ROOT/docker/scripts:/scripts:ro"
    echo "      - $ROOT:/workspace:ro"
    echo "      - $ROOT/artifacts:/workspace/artifacts"
    echo "      - $ROOT/packages/theme-core:/var/www/html/wp-content/packages/theme-core"
    if [[ "${WEB_MARKETPLACE:-0}" == 1 ]]; then
      echo "      - $ROOT/artifacts/package/$theme:/var/www/html/wp-content/themes/$theme:ro"
      echo "      - $ROOT/artifacts/plugins/jooservices-resume:/var/www/html/wp-content/plugins/jooservices-resume:ro"
    else
      for dir in "$ROOT"/themes/*/; do
        slug="$(basename "$dir")"
        echo "      - $ROOT/themes/$slug:/var/www/html/wp-content/themes/$slug"
      done
      for dir in "$ROOT"/plugins/*/; do
        [[ -d "$dir" ]] || continue
        slug="$(basename "$dir")"
        echo "      - $ROOT/plugins/$slug:/var/www/html/wp-content/plugins/$slug"
      done
      # Plugins staged by tools/build-plugin.mjs that have no source folder in this repository.
      for dir in "$ROOT"/artifacts/plugins/*/; do
        [[ -d "$dir" ]] || continue
        slug="$(basename "$dir")"
        [[ -d "$ROOT/plugins/$slug" ]] && continue
        echo "      - $ROOT/artifacts/plugins/$slug:/var/www/html/wp-content/plugins/$slug"
      done
    fi
    echo "volumes:"
    echo "  wp_uploads:"
    echo "    name: $uploads"
    echo "  php_logs:"
    echo "    name: joowt-wp-shared-test_php_logs"
    echo "  wp_tests_lib:"
    echo "    name: joowt-wp-shared-test_wp_tests_lib"
  } > "$web_override"
  chmod 600 "$web_override"
}

web_env() {
  export WEB_DB_NAME="$(get_env DB_NAME)" WEB_DB_USER="$(get_env DB_USER)" WEB_DB_PASSWORD="$(get_env DB_PASSWORD)"
  export WEB_SITE_URL="$(web_site_url)" WEB_ADMIN_USER="$(get_env WP_ADMIN_USER)" WEB_ADMIN_PASSWORD="$(get_env WP_ADMIN_PASSWORD)"
  export WEB_ADMIN_EMAIL="$(get_env WP_ADMIN_EMAIL)" WEB_WP_VERSION="${WP_VERSION:-$(get_env WP_VERSION)}"
  export WP_WEB_PORT="$(bash "$ROOT/docker/scripts/site-url.sh" port "$(web_site_url)")"
}

# Fresh web container and web root (the equivalent of a renewed core volume), WordPress downloaded and configured.
web_start() {
  web_env
  web_write_override
  docker image inspect "workspaces/php-app:$WP_WEB_PHP" >/dev/null 2>&1 || web_shared cli-build "php-${WP_WEB_PHP}-app"
  web_shared runtimes-up mailpit >/dev/null
  web_shared web-down --reset >/dev/null 2>&1 || true
  web_shared web-up "$web_override"
  docker exec -u root "$WEB_NAME" bash /scripts/web-bootstrap.sh root
  webx bash /scripts/web-bootstrap.sh user
}

web_down() { web_shared web-down "$@"; }

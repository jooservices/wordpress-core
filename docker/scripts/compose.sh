#!/usr/bin/env bash
# Wrapper around docker compose for this project: loads .env, derives the WordPress image tag.
# Shell environment variables (for example WP_VERSION=6.6) override values in .env.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"
[ -f .env ] || { echo "ERROR: .env is missing. Run: make init-env" >&2; exit 1; }
env_value() { grep -E "^$1=" .env | head -1 | cut -d= -f2-; }
WP_VERSION="${WP_VERSION:-$(env_value WP_VERSION)}"
WP_VERSION="${WP_VERSION:-latest}"
if [ "$WP_VERSION" = "latest" ]; then export WP_IMAGE_TAG="php8.3-apache"; else export WP_IMAGE_TAG="${WP_VERSION}-php8.3-apache"; fi
export WP_VERSION
export COMPOSE_PROJECT_NAME="${JOOWT_PROJECT:-jooservices-wp-themes}"
# Extra themes (scaffolded with make new-theme) are mounted through a generated override file.
EXTRA="docker/.themes.generated.yaml"
{
  echo "# generated by docker/scripts/compose.sh: do not edit"
  echo "services:"
  echo "  wordpress:"
  echo "    volumes:"
  for dir in themes/*/; do
    slug="$(basename "$dir")"
    case "$slug" in starter | jooservices) continue ;; esac
    echo "      - ../themes/${slug}:/var/www/html/wp-content/themes/${slug}"
  done
} >"${EXTRA}.tmp"
if [ "$(wc -l <"${EXTRA}.tmp")" -le 3 ]; then rm -f "${EXTRA}.tmp" "${EXTRA}"; else mv "${EXTRA}.tmp" "${EXTRA}"; fi
FILES=(-f docker/compose.yaml)
[ -f "${EXTRA}" ] && FILES+=(-f "${EXTRA}")
exec docker compose "${FILES[@]}" --env-file .env "$@"
